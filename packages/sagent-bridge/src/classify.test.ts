describe('classify: safe commands do not prompt', () => {
  it.each(safe)('%s', (command) => {
    expect(classify(command, ctx)).toMatchObject({ sensitive: false, reasons: [] })
  })
})

describe('classify: sensitive commands prompt with a reason', () => {
  it.each(sensitive)('%s -> %s', (command, reason) => {
    const result = classify(command, ctx)
    expect(result.sensitive).toBe(true)
    expect(result.reasons).toContain(reason)
  })
})

it('covers at least 70 cases', () => {
  expect(safe.length + sensitive.length).toBeGreaterThanOrEqual(70)
})

it('lists the command names it saw, unwrapping wrappers', () => {
  expect(classify('git status && sudo rm -rf x | cat', ctx).commands).toEqual(['git', 'sudo', 'rm', 'cat'])
})

it('paths inside the root through absolute form are fine', () => {
  expect(classify('cat /work/project/src/a.ts', ctx).sensitive).toBe(false)
  expect(classify('cat /work/project-evil/a.ts', ctx).reasons).toContain('path outside workspace')
})
